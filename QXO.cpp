  /**
   * Use the current Q-table to play against the XO class `AI'
   * @param player marker (1 [X] or 2 [O]) for the RL agent
   * @remark play cannot commence if specified player different than
   * trained player
   * @param N number of games to play
   * @remark There are only 26,830 legal games in tic-tac-toe so we limit the
   * number of games we can play accordingly by using std::uint16_t
   * @return a list of the number of wins, losses, and draws on the
   * part of the RL agent encountered during play
   */


std::array<std::uint16_t, 3> QXO::play(const std::uint8_t player, const std::uint16_t N) const {

    if (player != Q_mrk) {
        return std::array<std::uint16_t, 3>{0,0,0};
    }

    if (N > 26380) {
        return std::array<std::uint16_t, 3>{0, 0, 0};
    }


    std::array<std::uint16_t, 3> leaderboard = { 0,0,0 };

    for (std::size_t i = 0; i < N; i++) {
        XO game;

        if (player == 1) { // if agent is x, make x play first turn
            auto board = game.brd;
            auto it = Q_table.find(board);
            if (it == Q_table.end()) {
                throw std::runtime_error("Board state not found in Q-table.");
            }
            const auto& q_vals = Q_table.at(board);
            auto valid_moves = game.spaces(); // Get list of spaces in board
            if (valid_moves.empty()) {
                break; // No moves left
            }
            std::uint8_t move = argmax(q_vals);
            if (!game.move(Q_mrk, move)) {
                throw std::runtime_error("RL agent attempted an invalid move.");
            }
        }
        else { // opp is X
            auto moves_left = game.spaces();

            std::uniform_int_distribution<std::size_t> dist(0, moves_left.size() - 1);
            std::uint8_t random_move = moves_left[dist(const_cast<std::mt19937&>(g))];
            game.move(A_mrk, random_move);
        }


        while (!game.over()) {
            // Rl agent turn
            if (game.turn() == Q_mrk) {
                // get board state and retreive the qvals
                std::array<std::uint8_t, 9> board = game.brd;
                
                std::uint8_t best_move = 0;
                // get best move
                if (Q_table.find(board) != Q_table.end()) {
                    const auto& q_vals = Q_table.at(board);
                    auto valid_moves = game.spaces(); // Get list of spaces in board
                    if (valid_moves.empty()) {
                        break; // No moves left
                    }

                    best_move = argmax2(q_vals,valid_moves);

                }
                else {
                    auto moves_left = game.spaces();
                    std::uniform_int_distribution < std::size_t> dist(0, moves_left.size() - 1);
                    best_move = static_cast<std::uint8_t>(moves_left[dist(const_cast<std::mt19937&>(g))]);
                }

                game.move(Q_mrk, best_move);
            }
            else if (game.turn() == A_mrk) {

                auto moves_left = game.spaces();
                if (moves_left.size() == 0) {
                    break;
                }
                std::uniform_int_distribution<std::size_t> dist(0, moves_left.size() - 1);
                std::uint8_t random_move = moves_left[dist(const_cast<std::mt19937&>(g))];
                game.move(A_mrk, random_move);
            }


        }

        // after loop or game is over
        std::uint8_t winner = game.winner();
        if (winner == player) {
            leaderboard[0]++;
        }
        else if (winner == A_mrk)
            leaderboard[1]++;
        else {
            leaderboard[2]++;
        }


    }
    return leaderboard;
}

std::uint8_t QXO::argmax2(const std::array<float, 9>& actions, const std::vector<std::uint8_t>& valid_moves) const {


    float max_val = -std::numeric_limits<float>::infinity();
    std::size_t best_action = 0;

    for (std::size_t i = 0; i < actions.size(); i++) {
        if (std::find(valid_moves.begin(), valid_moves.end(), i) != valid_moves.end()) { // Check if move is valid
            if (actions[i] > max_val) {
                max_val = actions[i];
                best_action = i;
            }
        }
    }

    return best_action;
}

/**
 * Create/update the Q-table
 * @remark the Q-table is updated so long as model and game
 * parameters have not changed, otherwise it must be reinitialized
 * (changing epsilon for mini-batches would not constitute a change
 * in model parameters so long as epsilon is reset after training)
 * @param player marker (1 [X] or 2 [O]) for the RL agent
 * @param N number of games to play
 * @param N_batch number of games to play per mini-batch
 * @return a list of the number of wins, losses, and draws on the
 * part of the RL agent encountered during play
 */
std::array<std::uint16_t, 3> QXO::train(const std::uint8_t player, const std::uint16_t N, const std::uint16_t N_batch) {

    if (player != 1 && player != 2) {
        throw std::invalid_argument("invalid player value");
    }

    A_mrk = (player == 1) ? 2 : 1; // set a_mrk or opp to be x or O 
    Q_mrk = player;


    if (N % N_batch != 0) {
        throw std::invalid_argument("N must be divisible by N_batch");
    }

    std::size_t numbatches = N / N_batch;
    std::array<std::uint16_t, 3> leaderboard = { 0,0,0 }; // wins loss draw
    float startinge = epsilon;
    float epsilon_dec = epsilon / numbatches; // value to decrease epsilon by

    for (std::size_t i = 0; i < numbatches; i++) {
        for (std::size_t game_idx = 0; game_idx < N_batch; game_idx++) {


            XO game;
            uint8_t winner = update(game);

            if (winner == player) {
                leaderboard[0]++; // Win
            }
            else if (winner == A_mrk) {
                leaderboard[1]++; // Loss
            }
            else {
                leaderboard[2]++; // Draw
            }
        }

        // Decrease epsilon linearly
        epsilon -= epsilon_dec;
    }

    epsilon = startinge;
    return leaderboard;


}




//perform a 90 degree, clockwise rotation on the game board
std::array<std::uint8_t, 9> QXO::rotate(const std::array<std::uint8_t, 9>& board, std::uint8_t& move) const {
    std::array<std::uint8_t, 9> rotated;
    std::uint8_t temp = move;

    switch (temp) {
    case 0:
        move = 2;
        break;
    case 1:
        move = 5;
        break;
    case 2:
        move = 8;
        break;
    case 3:
        move = 1;
        break;
    case 4:
        move = 4;
        break;
    case 5:
        move = 7;
        break;
    case 6:
        move = 0;
        break;
    case 7:
        move = 3;
        break;
    case 8:
        move = 6;
        break;
    }


    rotated[0] = board[6];
    rotated[1] = board[3];
    rotated[2] = board[0];
    rotated[3] = board[7];
    rotated[4] = board[4];
    rotated[5] = board[1];
    rotated[6] = board[8];
    rotated[7] = board[5];
    rotated[8] = board[2];
    return rotated;

}




