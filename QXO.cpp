  /**
   * Update the Q-table based on the play and outcome of a single game
   * @param an instance of a tic-tac-toe game
   * @return the outcome of the game (0 := draw, 1 := player 1 [X]
   * win, 2 := player 2 [O] win)
   */
uint8_t QXO::update(XO& game) {

    // if game is over return reward
    if (game.over()) {
        return game.winner();
    }

    std::array<uint8_t, 9> board = game.brd;
    std::array<uint8_t, 9> baseboard = game.brd;

    if (Q_table.find(baseboard) == Q_table.end()) {
        Q_table[baseboard] = std::array<float, 9>{0.0f};
    }

    std::uint8_t move = 0;


    // agent plays first
    if (Q_mrk == 1) {

        
        if (dis(g) < epsilon) {
            // choose random mvove
            auto moves_left = game.spaces();
            std::uniform_int_distribution < std::size_t> dist(0, moves_left.size() - 1);
            move = static_cast<std::uint8_t>(moves_left[dist(g)]);

        }
        else {
            // use qtable to choose move
            move = argmax(Q_table[board]);

        }

        game.move(Q_mrk, move);
        // opp goes next
        
        if (!game.over()) {
            auto moves_left = game.spaces();
            std::uniform_int_distribution<std::size_t> dist(0, moves_left.size() - 1);
            std::uint8_t random_move = static_cast<std::uint8_t>(moves_left[dist(g)]);
            game.move(A_mrk, random_move);
        }
    }
    else if (A_mrk == 1) {

        // let opp go first if agent is not x
        
        auto moves_left = game.spaces();
        std::uniform_int_distribution<std::size_t> dist(0, moves_left.size() - 1);
        std::uint8_t random_move = static_cast<std::uint8_t>(moves_left[dist(g)]);
        game.move(A_mrk, random_move);

        //agent goes next
        
        if (!game.over()) {
            if (dis(g) < epsilon) {
                // choose random mvove
                auto moves_left = game.spaces();
                std::uniform_int_distribution < std::size_t> dist(0, moves_left.size() - 1);
                move = static_cast<std::uint8_t>(moves_left[dist(g)]);

            }
            else {
                // use qtable to choose move
                move = argmax(Q_table[board]);

            }

            game.move(Q_mrk, move);
        }
    }
    


    // opps turn


    nextboard.push_back(baseboard);

    // rec call to determine the next state outcome
    uint8_t outcome = update(game);

    auto futureboard = nextboard.back();

    nextboard.pop_back();

    // determin reward on the result of game
    float reward = (outcome == Q_mrk) ? 1.0f : (outcome == A_mrk ? -1.0f : 0.0f);

    //find maxq value for next state

    float next_maxq = 0.0f;
    if (Q_table.find(futureboard) != Q_table.end()) {
        next_maxq = *std::max_element(Q_table[futureboard].begin(), Q_table[futureboard].end());
    }
    Q_table[baseboard][move] = ((1 - alpha) * Q_table[baseboard][move]) + (alpha * (reward + gamma * next_maxq));
    std::uint8_t nextmove = move;
    auto nextbase = rotate(baseboard, nextmove);

    // rotate and get corres
    for (int i = 0; i < 3; i++) { //rotate 3 times

        Q_table[nextbase][nextmove] = Q_table[baseboard][move];

        std::uint8_t reflectedmove = nextmove;
        std::array<std::uint8_t, 9> reflected = reflect(nextbase, reflectedmove); //reflect current rotation

        Q_table[reflected][reflectedmove] = Q_table[baseboard][move];

        //rotate to next state
        nextbase = rotate(nextbase, nextmove);
    }


    return outcome;


}


// find max value and if theres a tie choose reandomly
std::uint8_t QXO::argmax(const std::array<float, 9>& actions) const {
    float max_val = actions[0];
    std::vector<std::size_t> candidates = { 0 };

    for (std::size_t i = 1; i < actions.size(); i++) {
        if (actions[i] > max_val) {
            max_val = actions[i];
            candidates.clear();
            candidates.push_back(i);
        }
        else if (actions[i] == max_val) {
            candidates.push_back(i); 
        }
    }

    // Randomly choose if there's a tie
    std::uniform_int_distribution<std::size_t> dist(0, candidates.size() - 1);
    return candidates[dist(const_cast<std::mt19937&>(g))];
}







