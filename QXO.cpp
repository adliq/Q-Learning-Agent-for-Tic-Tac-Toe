/**
   * Set the model parameters of the reinforcement learning agent
   * @param options values for alpha, epsilon, and gamma
   * @remark to ensure consistency in training, updating model
   * parameters should reset the Q-table
   * @return true if the provided model parameters were valid and set
   */
bool QXO::model(const Qopt& options) {

    if (options.alpha < 0.0f || options.alpha > 1.0f || options.epsilon < 0.0f || options.epsilon > 1.0f || options.gamma < 0.0f || options.gamma > 1.0f) {
        return false;
    }

    // check for parameter changes
    if (alpha != options.alpha || epsilon != options.epsilon || gamma != options.gamma) {

        Q_table.clear();
    }
    alpha = options.alpha;
    epsilon = options.epsilon;
    gamma = options.gamma;

    return true;
}


